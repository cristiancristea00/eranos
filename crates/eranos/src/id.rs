//! Identifiers for groups and their entries.
//!
//! Every identifier is a UUID v7: unique across devices, so entries created
//! offline on two phones never collide, and ordered by creation time.

use std::fmt;
use std::str::FromStr;
use std::sync::{Mutex, PoisonError};

use uuid::Uuid;

use crate::error::ValueError;

/// Held while an identifier is generated. uuid's shared v7 context reads the
/// clock before it takes its own lock, and when a thread is paused between
/// the two across a second boundary, its stale reading pushes the context's
/// timestamp almost a second ahead, so the identifiers generated once the
/// clock catches up sort before the earlier ones (uuid 1.26.1). Reading the
/// clock under this lock keeps every identifier eranos generates in creation
/// order. It guards no data, so a thread that panicked while holding it
/// leaves nothing to recover.
static GENERATION: Mutex<()> = Mutex::new(());

/// A new UUID v7, generated under [`GENERATION`].
fn generate_uuid() -> Uuid {
    let generating = GENERATION.lock().unwrap_or_else(PoisonError::into_inner);
    let uuid = Uuid::now_v7();
    drop(generating);
    uuid
}

macro_rules! define_id {
    ($(#[$meta:meta])* $name:ident) => {
        $(#[$meta])*
        ///
        /// The text form is the hyphenated UUID, and ordering follows creation
        /// time.
        ///
        /// # Examples
        ///
        /// ```
        #[doc = concat!("use eranos::id::", stringify!($name), ";")]
        ///
        #[doc = concat!("let id = ", stringify!($name), "::generate();")]
        #[doc = concat!("let parsed: ", stringify!($name), " = id.to_string().parse()?;")]
        /// assert_eq!(parsed, id);
        #[doc = concat!("assert_eq!(", stringify!($name), "::from_bytes(id.to_bytes()), id);")]
        /// # Ok::<(), eranos::error::ValueError>(())
        /// ```
        #[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
        #[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize), serde(transparent))]
        pub struct $name(Uuid);

        impl $name {
            /// Generates a new identifier from the current time and random
            /// bits.
            ///
            /// Identifiers generated by one process are strictly increasing.
            #[must_use]
            pub fn generate() -> Self {
                Self(generate_uuid())
            }

            /// Returns the identifier with these 16 bytes (big-endian UUID
            /// layout).
            #[must_use]
            pub const fn from_bytes(bytes: [u8; 16]) -> Self {
                Self(Uuid::from_bytes(bytes))
            }

            /// Returns the 16 bytes of the identifier (big-endian UUID
            /// layout).
            #[must_use]
            pub const fn to_bytes(self) -> [u8; 16] {
                self.0.into_bytes()
            }
        }

        impl fmt::Display for $name {
            fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
                fmt::Display::fmt(&self.0.hyphenated(), formatter)
            }
        }

        impl FromStr for $name {
            type Err = ValueError;

            /// Parses the hyphenated, simple, braced, or URN UUID text form.
            fn from_str(text: &str) -> Result<Self, Self::Err> {
                Uuid::try_parse(text.trim()).map(Self).map_err(|_| ValueError::InvalidId)
            }
        }
    };
}

define_id! {
    /// Identifies a [`Group`](crate::Group).
    GroupId
}

define_id! {
    /// Identifies a member of a group.
    MemberId
}

define_id! {
    /// Identifies a category of a group.
    CategoryId
}

impl CategoryId {
    /// The built-in category every expense has until it is given another,
    /// the same in every group: the nil UUID, which sorts before every
    /// generated identifier. The apps show its name in the user's language.
    pub const UNCATEGORISED: Self = Self(Uuid::nil());
}

define_id! {
    /// Identifies an expense of a group.
    ExpenseId
}

define_id! {
    /// Identifies a transfer (repayment) of a group.
    TransferId
}

